import { musicFixture } from './music-fixture.mjs';
import { selectRange } from './audio-helpers.mjs';
import { _electron as electron } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { encodeWave, decodeWave } from '../shared/audio.mjs';
const folder = await mkdtemp(path.join(os.tmpdir(), 'cation-interaction-'));
await mkdir('artifacts/audio', { recursive: true });
const rate = 44100, duration = 35, file = path.join(folder, 'interaction.wav');
const { channels } = musicFixture({ rate, seconds: duration });
await writeFile(file, encodeWave(channels, rate));
const app = await electron.launch({ executablePath: process.env.VIEWER_EXECUTABLE, args: [...(process.env.VIEWER_EXECUTABLE ? [] : ['.']), file, `--user-data-dir=${path.join(folder, 'profile')}`], env: { ...process.env, VITE_DEV_SERVER_URL: '' } });
try {
  const page = await app.firstWindow(), errors = []; page.setDefaultTimeout(15000); page.on('pageerror', e => errors.push(e.message));
  await page.waitForFunction(() => document.querySelector('.audio-workspace')?.dataset.name === 'interaction.wav');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1100, 760));
  await page.evaluate(() => {
    const start = AudioBufferSourceNode.prototype.start, stop = AudioBufferSourceNode.prototype.stop;
    AudioBufferSourceNode.prototype.stop = function (...args) { window.sourceStops = (window.sourceStops || 0) + 1; return stop.apply(this, args); };
    AudioBufferSourceNode.prototype.start = function (...args) { window.lastSource = this; window.lastStart = args; window.sourceStarts = (window.sourceStarts || 0) + 1; return start.apply(this, args); };
  });
  const source = () => page.evaluate(() => ({ loop: window.lastSource.loop, start: window.lastSource.loopStart, end: window.lastSource.loopEnd, offset: window.lastStart[1], count: window.sourceStarts, stops: window.sourceStops || 0 }));
  const waitJob = () => page.waitForFunction(() => document.querySelector('#loading').hidden);
  const select = (a, b) => selectRange(page, a, b, duration);
  const clickTime = async t => { const box = await page.locator('#audio-wave-area').boundingBox(); await page.mouse.click(box.x + 52 + (box.width - 54) * t / duration, box.y + box.height * .7); };
  const expectOutsideIgnored = async times => {
    const before = await source(), paused = await page.locator('#audio-play .icon-tabler-player-play').count();
    const clock = await page.locator('#audio-clock').textContent();
    const overlay = await page.locator('#audio-overlay').evaluate(canvas => canvas.toDataURL());
    for (const time of times) await clickTime(time);
    assert.deepEqual(await source(), before, 'Outside clicks must neither stop nor start a source or change its bounds');
    assert.equal(await page.locator('#audio-play .icon-tabler-player-play').count(), paused);
    if (paused) assert.equal(await page.locator('#audio-clock').textContent(), clock, 'Paused cursor must stay put');
    assert.equal(await page.locator('#audio-overlay').evaluate(canvas => canvas.toDataURL()), overlay);
  };
  const exportWave = async name => {
    const output = path.join(folder, `${name}.wav`);
    await app.evaluate(({ dialog, Menu }, output) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: output }); Menu.getApplicationMenu().items[0].submenu.items.find(i => i.label === 'Save as / Convert…').click(); }, output);
    await page.locator('#audio-format').selectOption('wav'); await page.locator('#audio-quality').selectOption('maximum'); await page.locator('#audio-export-selection').uncheck(); await page.locator('#audio-save').click(); await waitJob();
    await page.locator('#message button').click(); return decodeWave(new Uint8Array(await readFile(output)));
  };
  assert.equal(await page.locator('.audio-toolbar .audio-transport:last-child').count(), 1);
  assert.equal(await page.locator('.audio-bottom #audio-clock').count(), 1);
  for (const id of ['all', 'clear', 'trim', 'delete']) assert.equal(await page.locator(`.audio-toolbar #audio-${id}`).count(), 1);
  const sizes = await page.locator('#audio-play').evaluate(el => ({ button: parseFloat(getComputedStyle(el).width), icon: parseFloat(getComputedStyle(el.querySelector('svg')).width) }));
  assert.ok(Math.abs(sizes.button - 25.6) < .1); assert.equal(sizes.icon, 16);
  assert.equal(await page.locator('.audio-selection, #audio-in, #audio-out').count(), 0);
  assert.equal(await page.locator('#audio-fade-selection-in .icon-tabler-trending-up').count(), 1);
  assert.equal(await page.locator('#audio-fade-selection-out .icon-tabler-trending-down').count(), 1);
  const [selectionStart, selectionEnd] = await select(2, 6);
  const first = Math.round(selectionStart * rate), last = Math.round(selectionEnd * rate), middle = Math.floor((first + last) / 2); await page.screenshot({ path: 'artifacts/audio/yellow-selection.png' });
  assert.equal(await page.locator('#audio-overlay').evaluate(el => getComputedStyle(el).getPropertyValue('--audio-selection').trim()), '#ffdb57');
  await page.locator('#audio-fade-selection-in').click(); await waitJob();
  const fadedIn = (await exportWave('fade-in')).channels;
  for (let c = 0; c < 2; c++) {
    assert.deepEqual(fadedIn[c].slice(0, first), channels[c].slice(0, first));
    assert.deepEqual(fadedIn[c].slice(last), channels[c].slice(last));
    assert.equal(fadedIn[c][first], 0);
    assert.ok(Math.abs(fadedIn[c][middle] / channels[c][middle] - .5) < .001);
    assert.equal(fadedIn[c][last - 1], channels[c][last - 1]);
  }
  await page.locator('#audio-undo').click(); await page.locator('#audio-fade-selection-out').click(); await waitJob();
  const fadedOut = (await exportWave('fade-out')).channels;
  assert.equal(fadedOut[0][first], channels[0][first]); assert.equal(Math.abs(fadedOut[0][last - 1]), 0);
  await page.locator('#audio-undo').click(); await page.locator('#audio-clear').click();
  const [manualStart, manualEnd] = await select(2, 6);
  await page.locator('#audio-play').click();
  const beforePlainSeek = (await source()).count; await clickTime(4);
  await page.waitForFunction(count => window.sourceStarts > count, beforePlainSeek);
  assert.equal((await source()).loop, false); assert.equal((await source()).start, manualStart); assert.equal((await source()).end, manualEnd);
  assert.ok(Math.abs((await source()).offset - 4) < .1);
  await page.locator('#audio-play').click(); const plainPausedStarts = (await source()).count;
  await clickTime(5); assert.equal((await source()).count, plainPausedStarts);
  assert.equal(await page.locator('#audio-trim').isDisabled(), false);
  await page.locator('#audio-play').click(); assert.equal((await source()).start, manualStart); assert.equal((await source()).end, manualEnd);
  await page.locator('#audio-stop').click();
  await page.locator('#audio-loop').click(); await page.locator('#audio-play').click();
  const manualOverlay = await page.locator('#audio-overlay').evaluate(canvas => canvas.toDataURL());
  const beforeManualSeek = (await source()).count; await clickTime(4);
  await page.waitForFunction(count => window.sourceStarts > count, beforeManualSeek);
  const manualSeek = await source();
  assert.equal(manualSeek.loop, true); assert.equal(manualSeek.start, manualStart); assert.equal(manualSeek.end, manualEnd);
  assert.ok(Math.abs(manualSeek.offset - 4) < .1);
  assert.equal(await page.locator('#audio-overlay').evaluate(canvas => canvas.toDataURL()), manualOverlay, 'Seeking in a manual loop must preserve its visible selection');
  await page.locator('#audio-play').click(); const pausedStarts = (await source()).count;
  await clickTime(5); assert.equal((await source()).count, pausedStarts, 'Seeking while paused must stay paused');
  assert.equal(await page.locator('#audio-trim').isDisabled(), false);
  await page.locator('#audio-play').click(); assert.equal((await source()).start, manualStart); assert.equal((await source()).end, manualEnd);
  await expectOutsideIgnored([1, 23]);
  await page.locator('#audio-play').click(); await expectOutsideIgnored([1, 23]);
  await page.locator('#audio-stop').click(); await expectOutsideIgnored([1, 23]);
  await page.locator('#audio-play').click();
  await page.screenshot({ path: 'artifacts/audio/manual-loop-seek.png' });
  await page.locator('#audio-loop').click();
  const beforeReleased = (await source()).count; await clickTime(23);
  await page.waitForFunction(count => window.sourceStarts > count, beforeReleased);
  assert.equal((await source()).loop, false); assert.equal((await source()).start, 0); assert.equal((await source()).end, duration);
  await page.locator('#audio-stop').click(); await page.locator('#audio-clear').click();
  await page.locator('#audio-play').click(); await page.waitForFunction(() => window.lastSource);
  const beforeSeek = (await source()).count; await clickTime(23);
  await page.waitForFunction(count => window.sourceStarts > count, beforeSeek);
  assert.ok((await source()).offset > 22.8); assert.equal(await page.locator('#audio-play .icon-tabler-player-pause').count(), 1);
  await page.locator('#audio-stop').click(); await page.locator('#audio-clear').click();
  await page.waitForTimeout(100);
  const normalWave = await page.locator('#audio-wave').evaluate(canvas => canvas.toDataURL());
  const expectNormalWave = async () => {
    await page.waitForTimeout(100);
    const actual = await page.locator('#audio-wave').evaluate(canvas => canvas.toDataURL());
    if (actual !== normalWave) {
      await writeFile('artifacts/audio/reset-expected.png', Buffer.from(normalWave.split(',')[1], 'base64'));
      await writeFile('artifacts/audio/reset-actual.png', Buffer.from(actual.split(',')[1], 'base64'));
    }
    assert.equal(actual === normalWave, true, 'Wave pixels must return to normal after releasing loop highlighting');
  };
  await page.locator('#audio-find-loops').click(); await waitJob();
  await page.locator('.audio-loop-region').first().waitFor();
  assert.notEqual(await page.locator('#audio-wave').evaluate(canvas => canvas.toDataURL()), normalWave);
  const regionCount = await page.locator('.audio-loop-region').count();
  await page.locator('#audio-find-loops').click(); await waitJob();
  assert.equal(await page.locator('.audio-loop-region').count(), regionCount, 'Repeated search must preserve region buttons');
  const blocks = await page.locator('.audio-loop-region').evaluateAll(nodes => nodes.map(n => ({ left: n.getBoundingClientRect().left, right: n.getBoundingClientRect().right, top: n.getBoundingClientRect().top })));
  for (let i = 1; i < blocks.length; i++) { assert.ok(blocks[i].left >= blocks[i - 1].right - .1); assert.equal(blocks[i].top, blocks[0].top); }
  await page.locator('.audio-loop-region').first().click(); const locked = await source();
  assert.equal(locked.loop, true); assert.ok(locked.end - locked.start <= 20);
  const outsideTimes = [locked.start / 2, (locked.end + duration) / 2];
  await expectOutsideIgnored(outsideTimes);
  await page.locator('#audio-play').click(); await expectOutsideIgnored(outsideTimes);
  await page.locator('#audio-stop').click(); await expectOutsideIgnored(outsideTimes);
  await page.locator('#audio-play').click();
  await page.screenshot({ path: 'artifacts/audio/unique-loops-locked.png' });
  await page.locator('.audio-loop-region').first().click();
  assert.equal((await source()).loop, false); assert.equal((await source()).end, duration);
  await expectNormalWave();
  await page.locator('.audio-loop-region').first().click(); await page.locator('#audio-loop').click();
  assert.equal(await page.locator('.audio-loop-region[aria-pressed=true]').count(), 0);
  await expectNormalWave();
  await clickTime(34); assert.equal((await source()).loop, false); assert.ok((await source()).offset > 33.8);
  await page.locator('#audio-stop').click();
  await page.locator('#audio-clear').click(); await page.locator('#audio-find-loops').click(); await waitJob();
  await page.locator('#audio-clear-loops').click(); await expectNormalWave();
  assert.equal(await page.locator('.audio-loop-region').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: yellow selection, 20% smaller toolbar, tools/order/status, full-selection fades with unchanged surrounding samples, click-to-seek while playing, preserved manual selection with loop on/off and paused, disjoint loops, locked playback, ignored outside clicks while playing/paused/stopped for manual and found loops, and both unlock controls.');
} catch (error) { console.error(error.message.slice(0, 1500)); throw error; }
finally { await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); }).catch(() => {}); await app.close(); }
